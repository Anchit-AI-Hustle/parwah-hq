const BY_ISO = new Map(COUNTRIES.map(c => [c[0], c]));

// The ambulance number for a country code (ISO), 112 when unknown.
export function ambulanceFor(iso) {
  const c = BY_ISO.get(String(iso || '').toUpperCase());
  return c ? c[3] : '112';
}

export function countryName(iso) {
  const c = BY_ISO.get(String(iso || '').toUpperCase());
  return c ? c[1] : null;
}

export function isCountry(iso) {
  return BY_ISO.has(String(iso || '').toUpperCase());
}

