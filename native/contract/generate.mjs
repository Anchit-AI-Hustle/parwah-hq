// THE CONTRACT THE NATIVE APPS ARE TESTED AGAINST, written by the server.
//
// Rules the apps apply before a round trip (which PINs are refused, and in
// what words) must be the server's rules exactly, or a phone accepts a PIN
// the server then refuses. Copying them by hand into Kotlin and Swift is how
// they drift. So the server's own functions write this file, the Android and
// iPhone test suites both read it, and the gate regenerates it and fails if
// the committed copy is stale.
//
//   node native/contract/generate.mjs           # write contract.json
//   node native/contract/generate.mjs --check   # exit 1 if it is stale
import { readFileSync, writeFileSync } from 'node:fs';
import { pinError, PIN_LEN } from '../../api/_auth.mjs';

const pins = {};
// Every 4-number PIN, and the shapes that are refused before the list.
for (let i = 0; i < 10000; i++) {
  const p = String(i).padStart(PIN_LEN, '0');
  const e = pinError(p);
  if (e) pins[p] = e;
}
for (const p of ['', '12', '123', '12345', '12a4', 'abcd', ' 482', '4829 ']) pins[p] = pinError(p);

const contract = {
  _note: 'Generated by native/contract/generate.mjs from api/. Do not edit by hand.',
  pin: { length: PIN_LEN, refused: pins },
};
const out = JSON.stringify(contract, null, 1) + '\n';
const path = new URL('./contract.json', import.meta.url);
if (process.argv.includes('--check')) {
  let now = '';
  try { now = readFileSync(path, 'utf8'); } catch (e) {}
  if (now !== out) { console.error('native/contract/contract.json is stale: run node native/contract/generate.mjs'); process.exit(1); }
  console.log('native contract: up to date');
} else {
  writeFileSync(path, out);
  console.log('native contract: written, ' + Object.keys(pins).length + ' refused PINs');
}
